// Regenerates src/voiceClips.ts and src/soundBank.ts from the design
// voice data and the wav files in assets/. Run: node scripts/gen-assets.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const designVoice = join(root, '..', 'docs', 'design', 'voice');
const clips = JSON.parse(readFileSync(join(designVoice, 'clips.json'), 'utf8')).clips;
const shipped = new Set(readdirSync(join(root, 'assets', 'voice')));

const lines = [
  '/* eslint-disable @typescript-eslint/no-require-imports -- Metro bundles static asset requires */',
  '// Generated by scripts/gen-assets.mjs. Do not edit by hand.',
  '// Arabic cues ship as text: the phone synthesises them on first launch.',
  'export interface CueText { en: string; ar: string; fr: string }',
  'export const cueText: Record<string, CueText> = {',
];
for (const cue of clips) {
  lines.push(`  ${cue.id}: { en: ${JSON.stringify(cue.en)}, ar: ${JSON.stringify(cue.ar)}, fr: ${JSON.stringify(cue.fr)} },`);
}
lines.push('};', '', 'export const cueClip: Record<string, { en: unknown; fr: unknown }> = {');
for (const cue of clips) {
  const en = `${cue.id}.en.wav`;
  const fr = `${cue.id}.fr.wav`;
  if (shipped.has(en) && shipped.has(fr)) {
    lines.push(`  ${cue.id}: { en: require('../assets/voice/${en}'), fr: require('../assets/voice/${fr}') },`);
  }
}
lines.push('};', '');
writeFileSync(join(root, 'src', 'voiceClips.ts'), lines.join('\n'));

const sounds = readdirSync(join(root, 'assets', 'sounds')).filter((f) => f.endsWith('.wav')).sort();
const bank = [
  '/* eslint-disable @typescript-eslint/no-require-imports -- Metro bundles static asset requires */',
  '// Generated by scripts/gen-assets.mjs. Do not edit by hand.',
  'export const soundAsset: Record<string, unknown> = {',
];
for (const file of sounds) {
  bank.push(`  ${JSON.stringify(file.replace(/\.wav$/, ''))}: require('../assets/sounds/${file}'),`);
}
bank.push('};', '');
writeFileSync(join(root, 'src', 'soundBank.ts'), bank.join('\n'));
console.log(`cues: ${clips.length}, sounds: ${sounds.length}`);
